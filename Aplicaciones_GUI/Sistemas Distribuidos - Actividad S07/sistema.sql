CREATE DATABASE IF NOT EXISTS sistema;
USE sistema;

CREATE TABLE usuarios (
    ItemAi INT AUTO_INCREMENT PRIMARY KEY,
    IdUsuario VARCHAR(20) DEFAULT '100000001',
    CodUsuario VARCHAR(20),
    Usuario VARCHAR(50),
    Password VARCHAR(50),
    Nombres VARCHAR(100),
    Apellidos VARCHAR(100),
    Email VARCHAR(100),
    Permisos VARCHAR(50), -- Administrador / Usuario Normal
    Estado INT, -- 0: Anulado, 1: Activo, 2: Bloqueado
    Enlinea INT DEFAULT 0, -- 0: Cerrada, 1: En sesión
    Num_Ingresos INT DEFAULT 0,
    Fec_Creacion DATE,
    Fec_Modificacion DATE,
    Fec_Eliminacion DATE,
    Fec_UltimoAcceso DATE,
    Creado_Por VARCHAR(50),
    Modificado_Por VARCHAR(50),
    Eliminado_Por VARCHAR(50),
    Hora_Creacion TIME,
    Hora_Modificacion TIME,
    Hora_Eliminacion TIME,
    Hora_UltimoAcceso TIME
);

